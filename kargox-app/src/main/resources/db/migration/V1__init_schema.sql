-- KargoX initial schema.
--
-- Owned by Flyway, not Hibernate: the app runs with spring.jpa.hibernate.ddl-auto=validate,
-- meaning Hibernate checks every entity's mapping matches these tables/columns exactly at
-- startup and fails fast if they've drifted, but never silently generates or alters DDL
-- itself. Column names follow Spring Boot's default camelCase -> snake_case mapping, so
-- they match what Hibernate expects without any @Column(name=...) overrides needed.
--
-- Every table carries the same four BaseEntity columns (id, created_at, updated_at,
-- deleted, version) - "deleted" backs the app's soft-delete pattern (rows are flagged,
-- never hard-deleted, so foreign keys below never need ON DELETE CASCADE), and "version"
-- backs Hibernate's optimistic locking (@Version), which is what protects against races
-- like two drivers accepting the same booking at once.

-- ============================================================================
-- users
-- ============================================================================
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    version             BIGINT NOT NULL DEFAULT 0,

    full_name           VARCHAR(255) NOT NULL,
    email               VARCHAR(255) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    phone_number        VARCHAR(50),
    role                VARCHAR(20) NOT NULL,
    email_verified      BOOLEAN NOT NULL DEFAULT FALSE,
    profile_photo_url   VARCHAR(500),
    active              BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at       TIMESTAMPTZ,
    average_rating      DOUBLE PRECISION,
    total_ratings       INTEGER,

    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_role CHECK (role IN ('CUSTOMER', 'DRIVER', 'ADMIN'))
);
CREATE INDEX idx_users_role ON users (role);

-- ============================================================================
-- saved_addresses
-- ============================================================================
CREATE TABLE saved_addresses (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    version             BIGINT NOT NULL DEFAULT 0,

    user_id             BIGINT NOT NULL REFERENCES users (id),
    label               VARCHAR(255),
    formatted_address   VARCHAR(500),
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION
);
CREATE INDEX idx_saved_addresses_user ON saved_addresses (user_id);

-- ============================================================================
-- drivers
-- ============================================================================
CREATE TABLE drivers (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ,
    deleted                 BOOLEAN NOT NULL DEFAULT FALSE,
    version                 BIGINT NOT NULL DEFAULT 0,

    user_id                 BIGINT NOT NULL REFERENCES users (id),
    status                  VARCHAR(30) NOT NULL DEFAULT 'PENDING_VERIFICATION',
    license_number          VARCHAR(100),
    license_document_url    VARCHAR(500),
    id_document_url         VARCHAR(500),
    documents_verified      BOOLEAN NOT NULL DEFAULT FALSE,
    current_latitude        DOUBLE PRECISION,
    current_longitude       DOUBLE PRECISION,
    last_location_update    TIMESTAMPTZ,
    average_rating          DOUBLE PRECISION,
    total_ratings           INTEGER,
    completed_deliveries    INTEGER,
    wallet_balance          DOUBLE PRECISION,

    CONSTRAINT uq_drivers_user UNIQUE (user_id),
    CONSTRAINT chk_drivers_status CHECK (status IN
        ('OFFLINE', 'ONLINE', 'ON_TRIP', 'SUSPENDED', 'PENDING_VERIFICATION'))
);
CREATE INDEX idx_drivers_status ON drivers (status);

-- ============================================================================
-- vehicles
-- ============================================================================
CREATE TABLE vehicles (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                  TIMESTAMPTZ NOT NULL,
    updated_at                  TIMESTAMPTZ,
    deleted                     BOOLEAN NOT NULL DEFAULT FALSE,
    version                     BIGINT NOT NULL DEFAULT 0,

    driver_id                   BIGINT NOT NULL REFERENCES drivers (id),
    type                        VARCHAR(20) NOT NULL,
    make                        VARCHAR(100),
    model                       VARCHAR(100),
    registration_number         VARCHAR(50),
    color                       VARCHAR(50),
    max_weight_kg               DOUBLE PRECISION,
    length_cm                   DOUBLE PRECISION,
    width_cm                    DOUBLE PRECISION,
    height_cm                   DOUBLE PRECISION,
    photo_url                   VARCHAR(500),
    active                      BOOLEAN NOT NULL DEFAULT TRUE,
    roadworthy_document_url     VARCHAR(500),
    documents_verified          BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_vehicles_type CHECK (type IN
        ('MOTORCYCLE', 'HATCHBACK', 'SEDAN', 'PICKUP_TRUCK', 'VAN', 'TRUCK'))
);
CREATE INDEX idx_vehicles_driver ON vehicles (driver_id);

-- ============================================================================
-- bookings
-- ============================================================================
CREATE TABLE bookings (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                      TIMESTAMPTZ NOT NULL,
    updated_at                      TIMESTAMPTZ,
    deleted                         BOOLEAN NOT NULL DEFAULT FALSE,
    version                         BIGINT NOT NULL DEFAULT 0,

    booking_reference               VARCHAR(50) NOT NULL,
    customer_id                     BIGINT NOT NULL REFERENCES users (id),
    driver_id                       BIGINT REFERENCES drivers (id),
    vehicle_id                      BIGINT REFERENCES vehicles (id),

    pickup_address                  VARCHAR(500),
    pickup_latitude                 DOUBLE PRECISION,
    pickup_longitude                DOUBLE PRECISION,
    destination_address             VARCHAR(500),
    destination_latitude            DOUBLE PRECISION,
    destination_longitude           DOUBLE PRECISION,

    recommended_vehicle_type        VARCHAR(20) NOT NULL,
    status                          VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',

    delivery_instructions           VARCHAR(1000),
    estimated_distance_km           DOUBLE PRECISION,
    estimated_duration_minutes      INTEGER,
    estimated_fare                  DOUBLE PRECISION,
    final_fare                      DOUBLE PRECISION,

    scheduled                       BOOLEAN NOT NULL DEFAULT FALSE,
    scheduled_for                   TIMESTAMPTZ,

    driver_assigned_at              TIMESTAMPTZ,
    driver_arrived_at               TIMESTAMPTZ,
    goods_collected_at              TIMESTAMPTZ,
    delivered_at                    TIMESTAMPTZ,
    completed_at                    TIMESTAMPTZ,
    cancelled_at                    TIMESTAMPTZ,
    cancellation_reason             VARCHAR(500),
    cancelled_by_role               VARCHAR(20),

    pickup_pin                      VARCHAR(10),
    pickup_photo_url                VARCHAR(500),
    pickup_signature_url            VARCHAR(500),
    delivery_otp                    VARCHAR(10),
    delivery_photo_url              VARCHAR(500),
    delivery_signature_url          VARCHAR(500),

    CONSTRAINT uq_bookings_reference UNIQUE (booking_reference),
    CONSTRAINT chk_bookings_recommended_vehicle CHECK (recommended_vehicle_type IN
        ('MOTORCYCLE', 'HATCHBACK', 'SEDAN', 'PICKUP_TRUCK', 'VAN', 'TRUCK')),
    CONSTRAINT chk_bookings_status CHECK (status IN
        ('REQUESTED', 'SEARCHING_DRIVER', 'DRIVER_ASSIGNED', 'DRIVER_EN_ROUTE', 'DRIVER_ARRIVED',
         'GOODS_COLLECTED', 'IN_TRANSIT', 'DELIVERED', 'COMPLETED', 'CANCELLED', 'NO_DRIVER_FOUND'))
);
CREATE INDEX idx_bookings_customer ON bookings (customer_id);
CREATE INDEX idx_bookings_driver ON bookings (driver_id);
CREATE INDEX idx_bookings_status ON bookings (status);
CREATE INDEX idx_bookings_created_at ON bookings (created_at);

-- ============================================================================
-- goods_items
-- ============================================================================
CREATE TABLE goods_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ,
    deleted         BOOLEAN NOT NULL DEFAULT FALSE,
    version         BIGINT NOT NULL DEFAULT 0,

    booking_id      BIGINT NOT NULL REFERENCES bookings (id),
    name            VARCHAR(255),
    category        VARCHAR(30),
    size_tier       VARCHAR(20) NOT NULL DEFAULT 'SMALL',
    quantity        INTEGER,
    fragile         BOOLEAN NOT NULL DEFAULT FALSE,
    photo_url       VARCHAR(500),

    CONSTRAINT chk_goods_items_category CHECK (category IS NULL OR category IN
        ('FURNITURE', 'APPLIANCES', 'PARCELS', 'DOCUMENTS', 'BUILDING_MATERIALS', 'OFFICE_EQUIPMENT',
         'ELECTRONICS', 'GROCERIES', 'BUSINESS_INVENTORY', 'PERSONAL_BELONGINGS', 'FRAGILE_ITEMS',
         'LARGE_CARGO', 'OTHER')),
    CONSTRAINT chk_goods_items_size_tier CHECK (size_tier IN ('SMALL', 'MEDIUM', 'LARGE'))
);
CREATE INDEX idx_goods_items_booking ON goods_items (booking_id);

-- ============================================================================
-- ratings
-- ============================================================================
CREATE TABLE ratings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    version             BIGINT NOT NULL DEFAULT 0,

    booking_id          BIGINT NOT NULL REFERENCES bookings (id),
    rated_by_user_id    BIGINT NOT NULL REFERENCES users (id),
    rated_by_role       VARCHAR(20) NOT NULL,
    score               INTEGER NOT NULL,
    comment             VARCHAR(1000),

    CONSTRAINT chk_ratings_role CHECK (rated_by_role IN ('CUSTOMER', 'DRIVER', 'ADMIN')),
    CONSTRAINT chk_ratings_score CHECK (score BETWEEN 1 AND 5)
);
CREATE INDEX idx_ratings_booking ON ratings (booking_id);

-- ============================================================================
-- payments
-- ============================================================================
CREATE TABLE payments (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ,
    deleted                 BOOLEAN NOT NULL DEFAULT FALSE,
    version                 BIGINT NOT NULL DEFAULT 0,

    booking_id              BIGINT NOT NULL REFERENCES bookings (id),
    amount                  DOUBLE PRECISION NOT NULL,
    currency                VARCHAR(10) DEFAULT 'ZAR',
    method                  VARCHAR(30) NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    mock_transaction_ref    VARCHAR(255),
    paid_at                 TIMESTAMPTZ,

    CONSTRAINT uq_payments_booking UNIQUE (booking_id),
    CONSTRAINT chk_payments_method CHECK (method IN
        ('MOCK_CARD', 'CASH', 'WALLET', 'BUSINESS_ACCOUNT')),
    CONSTRAINT chk_payments_status CHECK (status IN
        ('PENDING', 'AUTHORIZED', 'PAID', 'FAILED', 'REFUNDED'))
);
CREATE INDEX idx_payments_status ON payments (status);

-- ============================================================================
-- notifications
-- ============================================================================
CREATE TABLE notifications (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              TIMESTAMPTZ NOT NULL,
    updated_at              TIMESTAMPTZ,
    deleted                 BOOLEAN NOT NULL DEFAULT FALSE,
    version                 BIGINT NOT NULL DEFAULT 0,

    user_id                 BIGINT NOT NULL REFERENCES users (id),
    type                    VARCHAR(30) NOT NULL,
    title                   VARCHAR(255) NOT NULL,
    message                 VARCHAR(1000),
    related_booking_id      BIGINT,
    read                    BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_notifications_type CHECK (type IN
        ('DRIVER_ASSIGNED', 'DRIVER_ARRIVED', 'GOODS_COLLECTED', 'DELIVERY_COMPLETED',
         'PAYMENT_CONFIRMED', 'BOOKING_CANCELLED', 'NEW_BOOKING_REQUEST', 'GENERIC'))
);
CREATE INDEX idx_notifications_user ON notifications (user_id);
CREATE INDEX idx_notifications_user_unread ON notifications (user_id, read);

-- ============================================================================
-- audit_logs
-- ============================================================================
CREATE TABLE audit_logs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ NOT NULL,
    updated_at          TIMESTAMPTZ,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    version             BIGINT NOT NULL DEFAULT 0,

    actor_user_id       BIGINT,
    actor_email         VARCHAR(255),
    actor_role          VARCHAR(20),
    action              VARCHAR(100) NOT NULL,
    entity_type         VARCHAR(100),
    entity_id           BIGINT,
    details             VARCHAR(2000),
    ip_address          VARCHAR(50)
);
CREATE INDEX idx_audit_logs_created_at ON audit_logs (created_at);
CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id);

-- ============================================================================
-- refresh_tokens
-- ============================================================================
CREATE TABLE refresh_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ,
    deleted         BOOLEAN NOT NULL DEFAULT FALSE,
    version         BIGINT NOT NULL DEFAULT 0,

    user_id         BIGINT NOT NULL REFERENCES users (id),
    token           VARCHAR(512) NOT NULL,
    expires_at      TIMESTAMPTZ NOT NULL,
    revoked         BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uq_refresh_tokens_token UNIQUE (token)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
